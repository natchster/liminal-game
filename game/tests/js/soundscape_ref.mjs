// Reference data for game/tests/soundscape_ref.rs, from the real src/soundscape.js.
//
//   node game/tests/js/soundscape_ref.mjs /path/to/OpenCarole/src/soundscape.js > game/tests/data/soundscape_ref_data.rs
//
// Runs createSoundscape on a mock AudioContext (no audio, only the buffers
// and the rng matter) with the LCG from tools/audio-render.mjs, then records
// how many rng draws each api call makes and statistics of every generated
// reverb impulse response.
import { pathToFileURL } from 'url';

const src = process.argv[2];
if (!src) { console.error('usage: soundscape_ref.mjs <soundscape.js>'); process.exit(1); }
const { createSoundscape, REVERB_PRESETS } = await import(pathToFileURL(src).href);

const param = () => ({ value: 0, setValueAtTime() { return this; }, linearRampToValueAtTime() { return this; }, exponentialRampToValueAtTime() { return this; }, setTargetAtTime() { return this; }, cancelScheduledValues() { return this; } });
function mockAC(sr, captured) {
  const node = () => ({ connect() {}, disconnect() {}, start() {}, stop() {}, gain: param(), frequency: param(), detune: param(), Q: param(), pan: param(), positionX: param(), positionY: param(), positionZ: param(), playbackRate: param() });
  const P = new Proxy({}, { get: (_, k) => (k === 'then' ? undefined : param()) });
  return {
    sampleRate: sr, currentTime: 0, destination: node(),
    listener: { positionX: param(), positionY: param(), positionZ: param(), forwardX: param(), forwardY: param(), forwardZ: param(), upX: param(), upY: param(), upZ: param() },
    createGain: node, createOscillator: node, createBiquadFilter: node, createBufferSource: node, createPanner: node, createWaveShaper: node,
    createConvolver: () => { const n = node(); Object.defineProperty(n, 'buffer', { set(b) { captured.push(b); }, get() { return null; } }); return n; },
    createBuffer: (ch, len, rate) => { const d = [...Array(ch)].map(() => new Float32Array(len)); return { numberOfChannels: ch, length: len, sampleRate: rate, getChannelData: (c) => d[c] }; },
    _P: P,
  };
}
function irStats(b) {
  const chans = [];
  for (let c = 0; c < b.numberOfChannels; c++) {
    const d = b.getChannelData(c);
    let sum = 0, sumsq = 0, wsum = 0, maxAbs = 0, argMax = 0;
    for (let i = 0; i < d.length; i++) { const v = d[i]; sum += v; sumsq += v * v; wsum += v * ((i % 7) + 1); if (Math.abs(v) > maxAbs) { maxAbs = Math.abs(v); argMax = i; } }
    const samples = [];
    for (let k = 0; k < 24; k++) { const i = Math.floor(d.length * k / 24) + k; if (i < d.length) samples.push([i, d[i]]); }
    chans.push({ sum, sumsq, wsum, maxAbs, argMax, samples });
  }
  return { len: b.length, chans };
}
const f = (v) => { const s = String(v); return /[.eE]/.test(s) || /n/i.test(s) ? s : s + '.0'; };

let out = '// generated by game/tests/js/soundscape_ref.mjs from src/soundscape.js — do not edit\n';
out += 'pub struct IrRef { pub name: &\'static str, pub len: usize, pub chans: [ChRef; 2] }\n';
out += 'pub struct ChRef { pub sum: f64, pub sumsq: f64, pub wsum: f64, pub max_abs: f64, pub arg_max: usize, pub samples: &\'static [(usize, f32)] }\n';
out += 'pub struct SsRef { pub sr: f64, pub construct_draws: u64, pub irs: &\'static [IrRef], pub steps: &\'static [(&\'static str, u64)], pub final_seed: u32 }\n';
out += 'pub const REFS: &[SsRef] = &[\n';
const LOOP = (k) => ({ t60: 0.5 + 0.4 * k, damp: 0.8 - 0.06 * k, wet: 0.1 + 0.045 * k, pre: 0.004 + 0.006 * k, er: 6 - (k >> 1) });
for (const sr of [44100, 48000]) {
  let seed = 12345, draws = 0;
  const rng = () => { draws++; seed = (seed * 1664525 + 1013904223) >>> 0; return seed / 4294967296; };
  const captured = [];
  const AC = mockAC(sr, captured);
  const S = createSoundscape(AC, AC.destination, { rng });
  const constructDraws = draws;
  const irs = [];
  const names = Object.keys(REVERB_PRESETS);
  for (const n of names) { S.setZone(n, 1.2); irs.push([n, irStats(captured[captured.length - 1])]); }
  S.defineZone('loop3', LOOP(3)); S.setZone('loop3'); irs.push(['loop3', irStats(captured[captured.length - 1])]);
  const steps = [];
  const mark = (label) => steps.push([label, draws]);
  mark('zones');
  S.setZone('nonexistent'); mark('setZone fallback lobby (cached)');
  for (const s of ['carpet', 'wetcarpet', 'concrete', 'tile', 'office', 'stair', 'mud']) { S.footstep(s, 0.8); mark('footstep ' + s); }
  S.heartbeat(80, 4, 0); mark('heartbeat 80 4 0');
  S.heartbeat(92, 5, 1); mark('heartbeat 92 5 1');
  S.heartbeat(96, 4, 0.4); mark('heartbeat 96 4 0.4');
  S.knock(3, 0, 6, -3, 0.6); mark('knock');
  S.screech(1, 0.9); mark('screech');
  const v = S.createChildVoice(); mark('createChildVoice');
  for (const p of ['sob', 'please', 'help', 'downhere', 'wail', 'nope']) { v.say(p, 0.05, 1, 1); mark('say ' + p); }
  for (let i = 0; i < 400; i++) S.hum.update(0.5, 0, 3, -1, i % 3 ? 1 : 0.2);
  mark('hum.update x400');
  S.burst(S.world, 0, 0.1, 'lowpass', 500, 1, 0.1); mark('burst');
  S.tone(S.world, 0, 0.1, 500, 0.1); mark('tone');
  out += `  SsRef { sr: ${f(sr)}, construct_draws: ${constructDraws}, final_seed: ${seed},\n    irs: &[\n`;
  for (const [n, st] of irs) {
    out += `      IrRef { name: "${n}", len: ${st.len}, chans: [\n`;
    for (const c of st.chans) out += `        ChRef { sum: ${f(c.sum)}, sumsq: ${f(c.sumsq)}, wsum: ${f(c.wsum)}, max_abs: ${f(c.maxAbs)}, arg_max: ${c.argMax}, samples: &[${c.samples.map(([i, x]) => `(${i}, ${f(x)})`).join(', ')}] },\n`;
    out += '      ] },\n';
  }
  out += '    ],\n    steps: &[\n';
  for (const [l, d] of steps) out += `      ("${l}", ${d}),\n`;
  out += '    ] },\n';
}
out += '];\n';
process.stdout.write(out);
