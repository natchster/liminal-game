#!/usr/bin/env node
// Generates game/src/world_tables.rs from backrooms.js: the order of the
// themed() prop passes in buildWorld, PLACER_THEMES (as literal alternations),
// THEME_ALLOW, and the per-level timer resets of buildWorld.
//
//   node tools/world-tables.mjs [/path/to/OpenCarole]
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = path.dirname(fileURLToPath(import.meta.url));
const ROOT = process.argv[2] || '/Users/nohwan/Documents/Personal_Projects/OpenCarole';
const src = fs.readFileSync(path.join(ROOT, 'backrooms.js'), 'utf8');
const lines = src.split('\n');
const lineOf = (re, from = 0) => { for (let i = from; i < lines.length; i++) if (re.test(lines[i])) return i; throw new Error('not found: ' + re); };

// ---- buildWorld boundaries
const bw0 = lineOf(/^function buildWorld\(\)/);
const bw1 = lineOf(/^}/, bw0);
const body = lines.slice(bw0, bw1 + 1);
const themedCalls = [];
for (const l of body) { const m = l.match(/^  themed\((place[A-Za-z0-9_]+), dist\);/); if (m) themedCalls.push(m[1]); }
// every themed() call in buildWorld must be of that exact shape
const allThemed = body.filter((l) => /themed\(/.test(l) && !/^\s*\/\//.test(l)).length;
if (allThemed !== themedCalls.length) throw new Error(`themed shape mismatch ${allThemed} vs ${themedCalls.length}`);

// ---- the timer / envelope resets (`  fooTimer = 0;` lines of buildWorld)
const resets = [];
for (const l of body) { const m = l.match(/^\s+([A-Za-z0-9]+) = 0;\s*(\/\/.*)?$/); if (m) resets.push(m[1]); }
const snake = (s) => s.replace(/([a-z0-9])([A-Z])/g, '$1_$2').replace(/([A-Z])([A-Z][a-z])/g, '$1_$2').toLowerCase();

// ---- PLACER_THEMES
const t0 = lineOf(/^const PLACER_THEMES = \[/);
const t1 = lineOf(/^\];/, t0);
const themes = [];
for (const l of lines.slice(t0 + 1, t1)) {
  const m = l.match(/^\s+\['([a-z]+)',\s*\/(.*)\/\],?\s*$/);
  if (!m) throw new Error('theme line: ' + l);
  const alts = m[2] === '.' ? ['.'] : m[2].split('|');
  for (const a of alts) if (a !== '.' && /[\\^$.()?*+{}\[\]]/.test(a)) throw new Error('regex special char in ' + a);
  themes.push([m[1], alts]);
}
// ---- THEME_ALLOW
const a0 = lineOf(/^const THEME_ALLOW = \{/);
const a1 = lineOf(/^\};/, a0);
const allow = [];
for (const l of lines.slice(a0 + 1, a1)) {
  const m = l.match(/^\s+([a-z]+):\s*\{([^}]*)\}/);
  if (!m) throw new Error('allow line: ' + l);
  const kv = m[2].split(',').map((s) => s.trim()).filter(Boolean).map((s) => { const [k, v] = s.split(':').map((x) => x.trim()); return [k, v]; });
  allow.push([m[1], kv]);
}
const ps0 = lineOf(/^const PLACER_ALWAYS = new Set\(\[/);
const always = [...lines[ps0].matchAll(/'([A-Za-z0-9_]+)'/g)].map((m) => m[1]);

const f = (v) => (v.includes('.') ? v : v + '.0');
let out = '';
out += '//! Generated by tools/world-tables.mjs from backrooms.js — do not edit.\n';
out += '//! The themed() prop passes of buildWorld in call order, PLACER_THEMES,\n';
out += '//! THEME_ALLOW, PLACER_ALWAYS and the per-level timer resets.\n\n';
out += `/// \`themed(placeX, dist)\` calls of buildWorld (lines ${bw0 + 1}–${bw1 + 1}), in order (${themedCalls.length}, with repeats)\n`;
out += `pub const THEMED_ORDER: [&str; ${themedCalls.length}] = [\n`;
for (let i = 0; i < themedCalls.length; i += 4) out += '    ' + themedCalls.slice(i, i + 4).map((n) => `"${n}"`).join(', ') + ',\n';
out += '];\n\n';
out += `/// \`PLACER_THEMES\` (line ${t0 + 1}): each regex is a plain alternation of\n/// literals (\`/./\` = any non-empty name), tested on the name without \`place\`.\n`;
out += `pub const PLACER_THEMES: [(&str, &[&str]); ${themes.length}] = [\n`;
for (const [k, alts] of themes) {
  out += `    ("${k}", &[`;
  let col = 0;
  out += alts.map((a) => `"${a}"`).join(', ');
  out += ']),\n';
}
out += '];\n\n';
out += `/// \`THEME_ALLOW\` (line ${a0 + 1}): zone archetype → (theme, chance)\n`;
out += `pub const THEME_ALLOW: [(&str, &[(&str, f64)]); ${allow.length}] = [\n`;
for (const [k, kv] of allow) out += `    ("${k}", &[${kv.map(([t, v]) => `("${t}", ${f(v)})`).join(', ')}]),\n`;
out += '];\n\n';
out += `/// \`PLACER_ALWAYS\` (line ${ps0 + 1})\n`;
out += `pub const PLACER_ALWAYS: [&str; ${always.length}] = [${always.map((n) => `"${n}"`).join(', ')}];\n\n`;
out += '/// buildWorld\'s per-level resets of the ambient timers and envelopes (`fooTimer = 0`), in order\n';
out += 'pub fn reset_level_timers(g: &mut crate::game::Game) {\n';
for (const r of resets) out += `    g.${snake(r)} = 0.0; // ${r}\n`;
out += '}\n';
fs.writeFileSync(path.join(HERE, '..', 'game', 'src', 'world_tables.rs'), out);
console.log(`themed ${themedCalls.length} (${new Set(themedCalls).size} unique), themes ${themes.length}, allow ${allow.length}, resets ${resets.length}`);
